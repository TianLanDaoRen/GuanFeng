package com.yisiyun.guanfeng.ui.theme

import androidx.compose.ui.graphics.Color

/**
 * 白色文字只有**三档明度**。
 *
 * ## 规则（主人 2026-09-12 定）
 *
 * 手表屏幕小、亮度低、离眼睛远，灰阶一多只会让"该看的东西"沉下去。
 * 所以所有**中性白/灰**的文字只用三档，全部偏亮：
 *
 * | 档 | 色值 | 用在哪 |
 * |---|---|---|
 * | [INK_LOW] 低 | `#D0D0D0` | **不重要、说明、信息类**：来源署名、单位、提示、禁用态 |
 * | [INK_MID] 中 | `#DCDCDC` | 标签、副标题、需要看清但不是主角的文字 |
 * | [INK_HIGH] 高 | `#E8E8E8` | 主角：数值、正文、当前状态 |
 *
 * **大部分白字都该用中或高**；只有真的可以"知道就行"的文字才允许低。
 * 最容易被写坏的正是副标题——它以前是 `#6E6E6E`，在手表上几乎是"看得见但读不清"，
 * 现在归到中档。
 *
 * ## 这三档是怎么定出来的
 *
 * 不是配色理论推的，是**主人指着屏幕上的实物**定的：
 *   · 逐日横条里 `20°/27°` 那行数字的亮度 = **低档锚点**
 *   · 逐小时列表里那行文字的亮度 = **高档锚点**
 *   · 中档 = 这两个锚点的正中间
 * 所以低档不是"越暗越好"的下限，它是**允许的最暗值**；
 * 高档也不是纯白（纯白在手表上会发糊），就是逐小时那行的亮度。
 *
 * ## 别绕过去
 *
 * 直接写 `Color(0xFF8A8A8A)` 这种第五、第六种灰是被 [WhiteTextTierTest] 拦下的——
 * 那条测试扫的是缩进后的界面源码，违规会带着行号报出来。
 * 深色（`#40` 以下）留给背景、分隔线、底纹，不受此限。
 */
val INK_LOW = Color(0xFFD0D0D0)

/** 中档：标签、副标题、需要看清但不是主角的文字。 */
val INK_MID = Color(0xFFDCDCDC)

/** 高档：数值、正文、当前状态。 */
val INK_HIGH = Color(0xFFE8E8E8)
